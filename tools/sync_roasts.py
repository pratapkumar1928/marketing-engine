"""Copy ScrollSmack's roast lines verbatim from the (private) app repo's strings.xml.

Usage: python tools/sync_roasts.py <path/to/strings.xml>
Writes apps/scrollsmack/copy/roasts.yaml. Re-run whenever the app's roast lines change.
"""
import re
import sys
import xml.etree.ElementTree as ET
from pathlib import Path

import yaml

OUT = Path(__file__).resolve().parent.parent / "apps" / "scrollsmack" / "copy" / "roasts.yaml"


def _android(s: str) -> str:
    return re.sub(r"\\(['\"])", r"\1", (s or "").strip())


def parse(xml_text: str) -> list[dict]:
    root = ET.fromstring(xml_text)
    names = {e.get("name"): _android(e.text) for e in root.iter("string")}
    arrays = {e.get("name"): [_android(i.text) for i in e.iter("item")] for e in root.iter("string-array")}
    out = []
    for name, heads in arrays.items():
        m = re.fullmatch(r"roast_(\w+)_headline", name)
        if not m:
            continue
        p = m.group(1)
        subs = arrays[f"roast_{p}"]
        assert len(subs) == len(heads), f"roast_{p}: headline/subtitle arrays differ in length"
        for i, (h, s) in enumerate(zip(heads, subs)):
            out.append({"id": f"{p}-{i}", "persona": names[f"persona_{p}"], "headline": h, "subtitle": s})
    return out


if __name__ == "__main__":
    items = parse(Path(sys.argv[1]).read_text(encoding="utf-8"))
    OUT.parent.mkdir(parents=True, exist_ok=True)
    OUT.write_text("# Generated by tools/sync_roasts.py from scrollsmack strings.xml. Do not edit by hand.\n"
                   + yaml.safe_dump(items, allow_unicode=True, sort_keys=False), encoding="utf-8")
    print(f"wrote {len(items)} roast lines to {OUT}")
